export function formatDotsDescription(dots: number[]): string {
  if (dots.length === 0) return 'no dots';
  if (dots.length === 1) return `Dot ${dots[0]}`;
  const sorted = [...dots].sort((a, b) => a - b);
  if (sorted.length === 2) return `Dots ${sorted[0]} and ${sorted[1]}`;
  const last = sorted[sorted.length - 1];
  const rest = sorted.slice(0, -1).join(', ');
  return `Dots ${rest}, and ${last}`;
}
